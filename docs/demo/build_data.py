#!/usr/bin/env python3
"""Rebuild data.js from the recorded run, byte for byte (python 3, no install).

    python3 docs/demo/build_data.py            # writes docs/demo/data.js
    python3 docs/demo/build_data.py --check    # only checks that data.js is current

data.js holds a COPY of three files from docs/evidence/flagship-run3/:
decisions.jsonl, decisions.jsonl.head.json and real3.log. Nothing is retyped.
The page recomputes everything it shows from these copies.
"""
import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
RUN = HERE.parent / "evidence" / "flagship-run3"
SOURCES = [
    ("decisions", "decisions.jsonl"),
    ("head", "decisions.jsonl.head.json"),
    ("log", "real3.log"),
]


def js_text(raw):
    """A JavaScript expression that rebuilds the file exactly (one source line per file line)."""
    text = raw.decode("ascii")  # fails loudly if the file is not plain ASCII
    pieces = text.split("\n")  # "a\nb\n" -> ["a", "b", ""]; join("\n") gives it back
    assert "\n".join(pieces) == text
    body = ",\n    ".join(json.dumps(p) for p in pieces)
    return "[\n    " + body + '\n  ].join("\\n")'


def build():
    out = [
        "/* Generated by build_data.py. Do not edit by hand.",
        " * A byte-for-byte copy of three files in docs/evidence/flagship-run3/.",
        " * Run `python3 docs/demo/build_data.py --check` to confirm it is current. */",
        "window.ANIMA_DATA = {",
    ]
    meta = {}
    for key, name in SOURCES:
        raw = (RUN / name).read_bytes()
        meta[name] = {"bytes": len(raw), "sha256": hashlib.sha256(raw).hexdigest()}
        out.append(f"  // {name}")
        out.append(f"  {key}: {js_text(raw)},")
    out.append("  // size and SHA-256 of each source file, measured when this file was generated")
    out.append("  sources: " + json.dumps(meta, indent=2).replace("\n", "\n  ") + ",")
    out.append("};")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    target = HERE / "data.js"
    text = build()
    if "--check" in sys.argv:
        same = target.exists() and target.read_text() == text
        print("data.js is current" if same else "data.js is OUT OF DATE")
        sys.exit(0 if same else 1)
    target.write_text(text)
    print(f"wrote {target} ({len(text)} bytes)")
